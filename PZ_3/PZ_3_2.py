"""Даны две переменные целого типа: A и B. Если их значения не равны, то присвоить каждой переменной большее из этих значений, а если равны, присвоить каждому значению 0.
Вывести новые значения переменных A и B"""

A = (input('Введите число: '))
B = (input('Введите число: '))
C = A

while True:
    try:
        A = int(A)
        B = int(B)
        break
    except ValueError:
        print("Неверное значение")
        A = (input('Введите число: '))
        B = (input('Введите число: '))

if A == B:
    A = 0
    B = 0
else:
    if A > B:
        A += A
        B += C
    else:
        A += B
        B += B

print(f"Итоговое значения A = {A}, B = {B}")